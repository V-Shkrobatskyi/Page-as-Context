export interface HfsLauncher { filename: string; content: string; needsExecutePermission: boolean }

const shellLauncher = `#!/bin/sh
# Copyright (c) 2026 Vitalii Shkrobatskyi
# SPDX-License-Identifier: GPL-3.0-only
# Start only the HFS executable and configuration beside this launcher.
set -eu
umask 077

fail() {
    printf '\\n%s\\n\\nPress Return to close this window.\\n' "$1"
    read -r answer || true
    exit 1
}

folder=$(CDPATH='' cd -P "$(dirname "$0")" && pwd -P) || exit 1
[ -f "$folder/hfs" ] || fail 'Missing hfs. Put this launcher beside the extracted HFS executable.'
[ -x "$folder/hfs" ] || fail 'The hfs file is not executable. Review its permissions before starting.'
[ -s "$folder/config.yaml" ] || fail 'Missing or empty config.yaml. Save the configuration generated by Page as Context in this folder.'

printf 'Starting HFS with configuration folder:\\n%s\\n\\nKeep this Terminal window open. Press Control-C to stop HFS.\\n\\n' "$folder"
exec "$folder/hfs" --cwd "$folder" --no-central
`;

const windowsLauncher = `@echo off
rem Copyright (c) 2026 Vitalii Shkrobatskyi
rem SPDX-License-Identifier: GPL-3.0-only
setlocal DisableDelayedExpansion
if not exist "%~dp0hfs.exe" goto missing_binary
if not exist "%~dp0config.yaml" goto missing_config
for %%I in ("%~dp0config.yaml") do if %%~zI==0 goto missing_config
echo Starting HFS. Keep this window open. Press Control-C to stop HFS.
"%~dp0hfs.exe" --cwd "%~dp0." --no-central
set "HFS_EXIT=%ERRORLEVEL%"
echo HFS stopped.
pause
exit /b %HFS_EXIT%

:missing_binary
echo Missing hfs.exe. Put this launcher beside the extracted HFS executable.
pause
exit /b 1

:missing_config
echo Missing or empty config.yaml. Save the configuration generated by Page as Context in this folder.
pause
exit /b 1
`;

/** Scripts contain no credentials or user-supplied shell text. Never execute them in the extension. */
export function hfsLauncher(os: string): HfsLauncher | undefined {
  if (os === 'mac' || os === 'linux') return { filename: os === 'mac' ? 'Start HFS.command' : 'start-hfs.sh', content: shellLauncher, needsExecutePermission: true };
  if (os === 'win') return { filename: 'Start HFS.cmd', content: windowsLauncher.replace(/\n/gu, '\r\n'), needsExecutePermission: false };
  return undefined;
}
