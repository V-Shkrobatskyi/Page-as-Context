import { describe, expect, it } from 'vitest';
import { COMPRESSION_LEVELS, EXPORT_PROFILES, prepareExport, type SemanticTree } from '@/src/core';
import { serializeMarkdown, countMarkdownCharacters, measureMarkdownEncoding } from '@/src/core/serializers/markdown';
import { serializeSemanticText, countSemanticTextCharacters, measureSemanticTextEncoding } from '@/src/core/serializers/semantic-text';

const tree: SemanticTree = {
  schemaVersion: 1, title: 'Workspace', sourceUrl: 'https://example.test/work', browser: 'Chrome', capturedAt: '2026.10.23 16:00:00',
  root: { role: 'RootWebArea', name: 'Workspace', href: 'https://example.test/work', children: [
    { role: 'region', name: 'Production', children: [{ role: 'button', name: 'Deploy', states: { disabled: true }, children: [] }] },
    { role: 'region', name: 'Staging', children: [{ role: 'button', name: 'Deploy', states: { disabled: false }, children: [] }] },
    { role: 'progressbar', name: 'Upload', value: '64', children: [] },
    { role: 'embedded-document', name: 'Captured frame', children: [{ role: 'RootWebArea', name: 'Frame', href: 'https://frame.test/', children: [] }] },
  ] },
};

describe('Agent context presentation', () => {
  for (const format of ['semantic-text', 'markdown'] as const) for (const level of COMPRESSION_LEVELS) {
    it(`${format}/${level}: keeps Standard stable and metadata, scope, state and notices in Agent context`, () => {
      const before = JSON.stringify(tree);
      const standard = prepareExport(tree, level, format, false);
      expect(prepareExport(tree, level, format, false, undefined, undefined, { profile: 'standard' })).toEqual(standard);
      const result = prepareExport(tree, level, format, false, undefined, undefined, { profile: 'agent-context', warnings: ['Canvas content is not included.'] });
      const text = result.serialized.content;
      expect(text).not.toContain('Generated by'); expect(text).not.toContain('Browser:'); expect(text).not.toContain('Captured:');
      expect(text.match(/Workspace/g)).toHaveLength(1); expect(text.match(/https:\/\/example.test\/work/g)).toHaveLength(1);
      for (const word of ['Production', 'Staging', 'Deploy', 'disabled=true', 'disabled=false', '64', 'embedded', 'Frame', 'frame.test', 'Canvas content is not included']) expect(text).toContain(word);
      expect(result.characterCount).toBe(text.length); expect(result.approximateTokenCount).toBe(Math.ceil(text.length / 4));
      const baseline = prepareExport(tree, 'without', format, false, undefined, undefined, { profile: 'agent-context', warnings: ['Canvas content is not included.'] });
      expect(result.reductionRatio).toBe(Math.max(0, 1 - text.length / baseline.characterCount));
      const block = prepareExport({ ...tree, selectedElementTag: 'section' }, level, format, false, undefined, undefined, { profile: 'agent-context' });
      expect(block.serialized.content).toContain('Selected block'); expect(block.serialized.content).toContain('section');
      expect(JSON.stringify(tree)).toBe(before);
    });
  }
  it.each(EXPORT_PROFILES)('%s: excludes metadata and values before creating headers', profile => {
    const sensitive = { ...tree, title: 'SECRET-TITLE', sourceUrl: 'https://example.test/?SECRET-QUERY', root: { role: 'page', children: [{ role: 'textbox', name: 'Account', value: 'SECRET-VALUE', children: [] }] } };
    for (const level of COMPRESSION_LEVELS) for (const format of ['semantic-text', 'markdown'] as const) {
      const result = prepareExport(sensitive, level, format, false, undefined, { includeTitle: false, includeFormValues: false, pageUrl: 'omit', linkUrls: 'omit' }, { profile });
      expect(result.serialized.content).not.toContain('SECRET');
    }
  });
  it('adds missing DOM source metadata without replacing a distinct accessible name', () => {
    const dom = { ...tree, root: { role: 'main', name: 'Accessible workspace name', children: [] } };
    for (const format of ['semantic-text', 'markdown'] as const) {
      const text = prepareExport(dom, 'without', format, false, undefined, undefined, { profile: 'agent-context' }).serialized.content;
      for (const value of ['Workspace', 'Accessible workspace name', 'https:']) expect(text).toContain(value);
    }
  });
  it('keeps count, measure, render and Maximum fallback on the same presentation', () => {
    for (const profile of EXPORT_PROFILES) {
      const options = { profile, warnings: ['Partial capture.'] };
      for (const [render, count, measure] of [[serializeSemanticText, countSemanticTextCharacters, measureSemanticTextEncoding], [serializeMarkdown, countMarkdownCharacters, measureMarkdownEncoding]] as const) {
        const text = render(tree, undefined, options).content;
        expect(count(tree, undefined, options)).toBe(text.length);
        expect(measure(tree, undefined, options).characters).toBe(text.length);
      }
    }
  });
});

it('keeps Maximum legends, references and source metadata in a packed Agent context export', () => {
  const repeated: SemanticTree = { ...tree, root: { ...tree.root, children: Array.from({length: 100}, () => ({ role: 'navigation', name: 'Shared deployment navigation', children: [{role:'link', name:'Review deployment configuration for all regions', href:'https://example.test/review', children:[]}] })) } };
  for (const format of ['semantic-text', 'markdown'] as const) {
    const text = prepareExport(repeated, 'maximum', format, false, undefined, undefined, {profile:'agent-context'}).serialized.content;
    expect(text).toContain('Encoding:'); expect(text).toContain('Strings:'); expect(text).toContain('A=');
    expect(text).toContain('Workspace'); expect(text).not.toContain('Generated by');
  }
});
